// ---------------------------------------------------------------- tuning

/**
 * The numbers that set the pace of the game. They live in one object so the
 * balance simulator can try alternatives; the game itself never changes them.
 * After replacing `surveys` at run time, call rebuildSurveyTable().
 */
export const TUNING = {
  /** Lumens from one tap on a common creature before any multiplier. */
  tapBase: 1,
  /** Every dive multiplies all income by this. */
  depthGrowth: 1.05,
  /** Entering a new zone multiplies all income by this on top. */
  zoneBonus: 2,
  /**
   * Lumens to earn at each depth before the next dive unlocks (index = dive
   * index). Generated by scripts/fit-surveys.ts from a pacing schedule; see
   * surveys.ts. Depths past the end of the list grow by surveyFallbackGrowth.
   */
  surveys: SURVEY_TARGETS as readonly number[],
  surveyFallbackGrowth: 1.6,
  /** A zone's hull costs this share of the last survey before it. */
  hullFactor: 0.5,
  /** First sighting of a species pays this many seconds of fleet income... */
  discoverySeconds: 1.5,
  /** ...or this many taps' worth, whichever is larger. */
  discoveryTaps: 3,
  /** Renown for publishing from the shallowest depth that allows it... */
  renownBase: 4.4,
  /** ...multiplied by this for every dive deeper the expedition reached. */
  renownGrowth: 1.14,
};

/** Seconds within which the next hit keeps a scan streak alive. */
export const COMBO_WINDOW = 1.6;
export const COMBO_STEP = 0.1;
/** A shoal creature is worth this many ordinary taps. */
export const SHOAL_VALUE = 5;
export const SHOAL_SIZE = 14;
export const SHOAL_DURATION = 13;
/** Mean seconds between shoals before upgrades. */
export const SHOAL_INTERVAL = 170;
export const FRENZY_SECONDS = 20;
export const FRENZY_CATCHES = 8;
export const SONAR_MULT = 2;
export const SONAR_SECONDS = 240;
/** Wait between free Sonar Bursts in builds without adverts. */
export const SONAR_COOLDOWN = 480;
/** Sonar Burst is offered once the player has dived this far at least once (50 m). */
export const SONAR_UNLOCK_STEP = 5;
export const BASE_OFFLINE_HOURS = 2;
export const BASE_OFFLINE_EFFICIENCY = 0.5;
/** Publishing needs a dive at least this deep in the current expedition (400 m). */
export const PRESTIGE_MIN_STEP = 28;
/** Zones beyond this need an Institute blueprint before their hull can be built. */
export const FREE_ZONE_LIMIT = 2;
/** Fleet Manager spends at most this share of the balance on one unit. */
export const AUTO_BUY_FRACTION = 0.04;

// ---------------------------------------------------------------- modifiers

export interface Modifiers {
  tapMult: number;
  globalMult: number;
  genMult: number[];
  resonance: number;
  comboCap: number;
  shoalRate: number;
  shoalMult: number;
  /** 0 when Feeding Frenzy has not been researched. */
  frenzyMult: number;
  /** Seconds between automatic scans; 0 when there are none. */
  autoScanInterval: number;
  diveDiscount: number;
  generatorDiscount: number;
  offlineHours: number;
  offlineEfficiency: number;
  codexPerLevel: number;
  rareChance: number;
  renownMult: number;
  studySpeed: number;
  seedBuoys: number;
  /** Deepest zone whose hull may be built. */
  unlockedZone: number;
  autoDive: boolean;
  autoBuy: boolean;
}

function baseModifiers(): Modifiers {
  return {
    tapMult: 1,
    globalMult: 1,
    genMult: GENERATORS.map(() => 1),
    resonance: 0,
    comboCap: 0,
    shoalRate: 1,
    shoalMult: 1,
    frenzyMult: 0,
    autoScanInterval: 0,
    diveDiscount: 1,
    generatorDiscount: 1,
    offlineHours: BASE_OFFLINE_HOURS,
    offlineEfficiency: BASE_OFFLINE_EFFICIENCY,
    codexPerLevel: 0.02,
    rareChance: 1,
    renownMult: 1,
    studySpeed: 1,
    seedBuoys: 0,
    unlockedZone: FREE_ZONE_LIMIT,
    autoDive: false,
    autoBuy: false,
  };
}

/** Applies one effect `levels` times. Multipliers compound; amounts add. */
function applyEffect(mods: Modifiers, effect: Effect, levels: number): void {
  switch (effect.kind) {
    case 'tapMult':
      mods.tapMult *= Math.pow(effect.value, levels);
      break;
    case 'globalMult':
      mods.globalMult *= Math.pow(effect.value, levels);
      break;
    case 'genMult':
      mods.genMult[effect.gen] = (mods.genMult[effect.gen] ?? 1) * Math.pow(effect.value, levels);
      break;
    case 'resonance':
      mods.resonance += effect.value * levels;
      break;
    case 'comboCap':
      mods.comboCap = Math.max(mods.comboCap, effect.value);
      break;
    case 'shoalRate':
      mods.shoalRate *= Math.pow(effect.value, levels);
      break;
    case 'shoalMult':
      mods.shoalMult *= Math.pow(effect.value, levels);
      break;
    case 'frenzy':
      mods.frenzyMult = Math.max(mods.frenzyMult, effect.value);
      break;
    case 'autoScanInterval':
      mods.autoScanInterval = mods.autoScanInterval === 0 ? effect.value : Math.min(mods.autoScanInterval, effect.value);
      break;
    case 'diveDiscount':
      mods.diveDiscount *= Math.pow(effect.value, levels);
      break;
    case 'generatorDiscount':
      mods.generatorDiscount *= Math.pow(effect.value, levels);
      break;
    case 'offlineHours':
      mods.offlineHours += effect.value * levels;
      // Night Shift also raises how much of the fleet's income counts while away.
      mods.offlineEfficiency = Math.min(1, mods.offlineEfficiency + 0.1 * levels);
      break;
    case 'offlineEfficiency':
      mods.offlineEfficiency = Math.min(1, mods.offlineEfficiency + effect.value * levels);
      break;
    case 'codexBonus':
      mods.codexPerLevel += effect.value * levels;
      break;
    case 'rareChance':
      mods.rareChance *= Math.pow(effect.value, levels);
      break;
    case 'renownMult':
      mods.renownMult += effect.value * levels;
      break;
    case 'studySpeed':
      mods.studySpeed *= Math.pow(effect.value, levels);
      break;
    case 'seedBuoys':
      mods.seedBuoys += effect.value * levels;
      break;
    case 'unlockZone':
      mods.unlockedZone = Math.max(mods.unlockedZone, effect.value);
      break;
    case 'autoDive':
      mods.autoDive = true;
      break;
    case 'autoBuy':
      mods.autoBuy = true;
      break;
  }
}

/** Far beyond anything ordinary play can reach, and far inside what a double can hold. */
const MAX_MULTIPLIER = 1e90;

const modifierCache = new WeakMap<GameState, Modifiers>();

/** Call after research or institute purchases, and after publishing. */
export function invalidateModifiers(state: GameState): void {
  modifierCache.delete(state);
}

export function getModifiers(state: GameState): Modifiers {
  const cached = modifierCache.get(state);
  if (cached) return cached;
  const mods = baseModifiers();
  for (const research of RESEARCH) {
    if (state.research[research.id]) applyEffect(mods, research.effect, 1);
  }
  for (const upgrade of INSTITUTE) {
    const level = Math.min(upgrade.maxLevel, state.institute[upgrade.id] ?? 0);
    if (level > 0) applyEffect(mods, upgrade.effect, level);
  }
  // Keep every multiplier finite whatever a save claims, so no number can become Infinity or NaN.
  mods.tapMult = Math.min(mods.tapMult, MAX_MULTIPLIER);
  mods.globalMult = Math.min(mods.globalMult, MAX_MULTIPLIER);
  modifierCache.set(state, mods);
  return mods;
}

// ---------------------------------------------------------------- depth

export function clampStep(step: number): number {
  return Math.max(0, Math.min(TOTAL_STEPS, Math.floor(step)));
}

/** The zone a dive index sits in. The sea floor counts as the last zone. */
export function zoneOfStep(step: number): number {
  const s = clampStep(step);
  for (let zone = ZONES.length - 1; zone >= 0; zone--) {
    if (s >= (ZONE_START_STEP[zone] as number)) return zone;
  }
  return 0;
}

export function depthOfStep(step: number): number {
  const s = clampStep(step);
  const zone = zoneOfStep(s);
  const def = ZONES[zone] as (typeof ZONES)[number];
  return Math.min(def.bottomDepth, def.topDepth + (s - (ZONE_START_STEP[zone] as number)) * def.stepMetres);
}

export function depthMultiplier(step: number): number {
  const s = clampStep(step);
  return Math.pow(TUNING.depthGrowth, s) * Math.pow(TUNING.zoneBonus, zoneOfStep(s));
}

let surveyTable: number[] | null = null;

/** Lumens needed at each depth before the next dive, before discounts. Index = dive index you are at. */
function surveyTargets(): number[] {
  if (!surveyTable) {
    const table: number[] = [];
    let target = TUNING.surveys[0] ?? 500;
    for (let step = 0; step < TOTAL_STEPS; step++) {
      const fitted = TUNING.surveys[step];
      if (fitted !== undefined) target = fitted;
      table.push(target);
      target *= TUNING.surveyFallbackGrowth;
    }
    surveyTable = table;
  }
  return surveyTable;
}

/** Recomputes survey sizes after TUNING has been changed (simulator use only). */
export function rebuildSurveyTable(): void {
  surveyTable = null;
}

export function atSeaFloor(state: GameState): boolean {
  return state.depthStep >= TOTAL_STEPS;
}

/**
 * The zone whose hull must be built before the next dive, or null when the
 * current hull is good for one more dive.
 */
export function hullNeeded(state: GameState): number | null {
  if (atSeaFloor(state)) return null;
  // A dive lands on depthStep + 1; the hull must be rated for the zone that step is in.
  const nextZone = zoneOfStep(state.depthStep + 1);
  return nextZone > state.hullZone ? nextZone : null;
}

/** Lumens price of the hull needed to enter a zone. */
export function hullCost(state: GameState, zone: number): number {
  const lastSurvey = surveyTargets()[(ZONE_START_STEP[zone] as number) - 1];
  if (zone <= 0 || zone >= ZONES.length || lastSurvey === undefined) return Infinity;
  return Math.ceil(lastSurvey * TUNING.hullFactor * getModifiers(state).diveDiscount);
}

/** True when an Institute blueprint is still missing for that zone's hull. */
export function hullLocked(state: GameState, zone: number): boolean {
  return zone > getModifiers(state).unlockedZone;
}

/** Lumens that must be earned at the current depth before the next dive. */
export function surveyTarget(state: GameState): number {
  const base = surveyTargets()[state.depthStep];
  if (base === undefined) return Infinity;
  return Math.max(1, Math.ceil(base * getModifiers(state).diveDiscount));
}

/** Survey progress at the current depth, from 0 to 1. */
export function surveyProgress(state: GameState): number {
  if (atSeaFloor(state)) return 1;
  return Math.max(0, Math.min(1, state.survey / surveyTarget(state)));
}

export function surveyComplete(state: GameState): boolean {
  return !atSeaFloor(state) && state.survey >= surveyTarget(state);
}

export type DiveBlock = 'floor' | 'survey' | 'hull' | null;

/** Why the sub cannot dive right now, or null when it can. */
export function diveBlock(state: GameState): DiveBlock {
  if (atSeaFloor(state)) return 'floor';
  if (!surveyComplete(state)) return 'survey';
  if (hullNeeded(state) !== null) return 'hull';
  return null;
}

// ---------------------------------------------------------------- codex and achievements

export function studyLevel(rarity: Rarity, scans: number): number {
  const thresholds = RARITIES[rarity].study;
  let level = 0;
  for (const threshold of thresholds) {
    if (scans >= threshold) level++;
  }
  return level;
}

/** Scans needed for the next study level, or null at the top level. */
export function nextStudyTarget(rarity: Rarity, scans: number): number | null {
  for (const threshold of RARITIES[rarity].study) {
    if (scans < threshold) return threshold;
  }
  return null;
}

export function speciesStudyLevel(state: GameState, speciesId: string): number {
  const species = SPECIES_BY_ID.get(speciesId);
  if (!species) return 0;
  return studyLevel(species.rarity, state.codex[speciesId] ?? 0);
}

export function totalStudyLevels(state: GameState): number {
  let total = 0;
  for (const species of SPECIES) total += studyLevel(species.rarity, state.codex[species.id] ?? 0);
  return total;
}

export const MAX_TOTAL_STUDY_LEVELS = SPECIES.length * MAX_STUDY_LEVEL;

export function speciesFound(state: GameState): number {
  let found = 0;
  for (const species of SPECIES) if ((state.codex[species.id] ?? 0) > 0) found++;
  return found;
}

export function codexMultiplier(state: GameState): number {
  return 1 + totalStudyLevels(state) * getModifiers(state).codexPerLevel;
}

export function achievementCount(state: GameState): number {
  return Object.keys(state.achievements).length;
}

export function achievementMultiplier(state: GameState): number {
  return 1 + achievementCount(state) * ACHIEVEMENT_BONUS;
}

// ---------------------------------------------------------------- income

export function sonarActive(state: GameState): boolean {
  return state.clock < state.sonarUntil;
}

export function frenzyActive(state: GameState): boolean {
  return state.clock < state.frenzyUntil;
}

export function boostMultiplier(state: GameState): number {
  const mods = getModifiers(state);
  return (sonarActive(state) ? SONAR_MULT : 1) * (frenzyActive(state) && mods.frenzyMult > 0 ? mods.frenzyMult : 1);
}

/** Multiplier applied to every source of lumens. `withBoosts` is false for offline maths. */
export function globalMultiplier(state: GameState, withBoosts = true): number {
  return (
    getModifiers(state).globalMult *
    depthMultiplier(state.depthStep) *
    codexMultiplier(state) *
    achievementMultiplier(state) *
    (withBoosts ? boostMultiplier(state) : 1)
  );
}

export function milestoneMultiplier(count: number): number {
  let multiplier = 1;
  for (const threshold of FLEET_MILESTONES) {
    if (count >= threshold) multiplier *= 2;
  }
  return multiplier;
}

export function nextMilestone(count: number): number | null {
  for (const threshold of FLEET_MILESTONES) {
    if (count < threshold) return threshold;
  }
  return null;
}

/** Lumens per second from all owned units of one generator. */
export function generatorRate(state: GameState, gen: number, withBoosts = true): number {
  const def = GENERATORS[gen];
  const count = state.generators[gen] ?? 0;
  if (!def || count <= 0) return 0;
  return def.baseRate * count * milestoneMultiplier(count) * (getModifiers(state).genMult[gen] ?? 1) * globalMultiplier(state, withBoosts);
}

export function fleetRate(state: GameState, withBoosts = true): number {
  let total = 0;
  for (let gen = 0; gen < GENERATORS.length; gen++) total += generatorRate(state, gen, withBoosts);
  return total;
}

export function comboMultiplier(state: GameState, streak: number): number {
  return 1 + Math.min(Math.max(0, streak), getModifiers(state).comboCap) * COMBO_STEP;
}

/** Lumens for one tap's worth of scanning on a common creature. */
export function tapValue(state: GameState, withBoosts = true): number {
  const mods = getModifiers(state);
  return TUNING.tapBase * mods.tapMult * globalMultiplier(state, withBoosts) + mods.resonance * fleetRate(state, withBoosts);
}

/** Lumens for finishing a scan of a creature of the given rarity. */
export function scanReward(state: GameState, rarity: Rarity, streak = 0, shoal = false): number {
  const mods = getModifiers(state);
  const base = tapValue(state) * comboMultiplier(state, streak);
  return shoal ? base * SHOAL_VALUE * mods.shoalMult : base * RARITIES[rarity].value;
}

/** Spawn weight of each rarity once Keen Eyes is counted. */
export function rarityWeights(state: GameState): Record<Rarity, number> {
  const boost = getModifiers(state).rareChance;
  return {
    common: RARITIES.common.weight,
    uncommon: RARITIES.uncommon.weight,
    rare: RARITIES.rare.weight * boost,
    legendary: RARITIES.legendary.weight * boost,
  };
}

/** Average lumens earned per tap across what spawns, in units of tapValue. */
export function averageValuePerTap(state: GameState): number {
  const weights = rarityWeights(state);
  let total = 0;
  let weightSum = 0;
  for (const rarity of Object.keys(RARITIES) as Rarity[]) {
    total += weights[rarity] * (RARITIES[rarity].value / RARITIES[rarity].taps);
    weightSum += weights[rarity];
  }
  return total / weightSum;
}

/** Estimated lumens per second from the fleet's automatic scans. */
export function autoScanRate(state: GameState, withBoosts = true): number {
  const interval = getModifiers(state).autoScanInterval;
  if (interval <= 0) return 0;
  return (tapValue(state, withBoosts) * averageValuePerTap(state)) / interval;
}

/** Lumens per second with nobody touching the game. */
export function passiveRate(state: GameState, withBoosts = true): number {
  return fleetRate(state, withBoosts) + autoScanRate(state, withBoosts);
}

export function discoveryBonus(state: GameState): number {
  return Math.max(TUNING.discoverySeconds * passiveRate(state), TUNING.discoveryTaps * tapValue(state));
}

// ---------------------------------------------------------------- fleet prices

export function generatorUnlocked(state: GameState, gen: number): boolean {
  const def = GENERATORS[gen];
  return !!def && state.maxStepEver >= def.unlockStep;
}

/** Price of the next `quantity` units of a generator. */
export function generatorCost(state: GameState, gen: number, quantity = 1): number {
  const def = GENERATORS[gen];
  if (!def || quantity <= 0) return Infinity;
  const owned = state.generators[gen] ?? 0;
  const first = def.baseCost * Math.pow(GENERATOR_COST_GROWTH, owned);
  const series = (Math.pow(GENERATOR_COST_GROWTH, quantity) - 1) / (GENERATOR_COST_GROWTH - 1);
  return Math.ceil(first * series * getModifiers(state).generatorDiscount);
}

/** How many units of a generator the current balance can pay for. */
export function maxAffordable(state: GameState, gen: number): number {
  const def = GENERATORS[gen];
  if (!def) return 0;
  const owned = state.generators[gen] ?? 0;
  const first = def.baseCost * Math.pow(GENERATOR_COST_GROWTH, owned) * getModifiers(state).generatorDiscount;
  if (!Number.isFinite(state.lumens) || !Number.isFinite(first) || !(first > 0) || state.lumens < first) return 0;
  const estimate = Math.floor(Math.log((state.lumens * (GENERATOR_COST_GROWTH - 1)) / first + 1) / Math.log(GENERATOR_COST_GROWTH));
  if (!Number.isFinite(estimate)) return 0;
  let quantity = Math.max(0, estimate);
  // The closed form can be off by one either way because prices are rounded up.
  // The corrections are bounded so that no input can keep them looping.
  for (let i = 0; i < 8 && quantity > 0 && generatorCost(state, gen, quantity) > state.lumens; i++) quantity--;
  for (let i = 0; i < 8 && generatorCost(state, gen, quantity + 1) <= state.lumens; i++) quantity++;
  return generatorCost(state, gen, quantity) <= state.lumens ? quantity : 0;
}

// ---------------------------------------------------------------- research and institute

export function researchVisible(state: GameState, research: ResearchDef): boolean {
  if (state.research[research.id]) return false;
  if (research.requiresStep !== undefined && state.stats.maxStepThisRun < research.requiresStep) return false;
  if (research.requiresGenerator && (state.generators[research.requiresGenerator.gen] ?? 0) < research.requiresGenerator.count) return false;
  return true;
}

/** Unbought research the player can currently see, cheapest first. */
export function availableResearch(state: GameState): ResearchDef[] {
  return RESEARCH.filter((research) => researchVisible(state, research)).sort((a, b) => a.cost - b.cost);
}

export function instituteLevel(state: GameState, id: string): number {
  return state.institute[id] ?? 0;
}

export function instituteVisible(state: GameState, upgrade: InstituteDef): boolean {
  return state.prestiges >= (upgrade.requiresPrestiges ?? 0);
}

/** Renown price of the next level, or Infinity when the upgrade is maxed. */
export function instituteCost(state: GameState, upgrade: InstituteDef): number {
  const level = instituteLevel(state, upgrade.id);
  if (level >= upgrade.maxLevel) return Infinity;
  return Math.ceil(upgrade.baseCost * Math.pow(upgrade.costGrowth, level));
}

// ---------------------------------------------------------------- publishing (prestige)

/**
 * Renown for publishing an expedition whose deepest dive was `step`. It
 * depends only on depth, so the rule a player needs is simple: go deeper,
 * earn more.
 */
export function renownAtStep(state: GameState, step: number): number {
  if (step < PRESTIGE_MIN_STEP) return 0;
  return Math.floor(TUNING.renownBase * Math.pow(TUNING.renownGrowth, step - PRESTIGE_MIN_STEP) * getModifiers(state).renownMult);
}

/** Renown the player would earn by surfacing now. */
export function renownOnPublish(state: GameState): number {
  return renownAtStep(state, state.stats.maxStepThisRun);
}

export function canPublish(state: GameState): boolean {
  return renownOnPublish(state) >= 1;
}

// ---------------------------------------------------------------- offline

export interface OfflineReport {
  /** Seconds actually away. */
  awaySeconds: number;
  /** Seconds that counted after the cap. */
  countedSeconds: number;
  efficiency: number;
  lumens: number;
}

/** What the fleet earned while the game was closed. Does not change state. */
export function offlineReport(state: GameState, nowMs: number): OfflineReport | null {
  if (!state.lastSeen || nowMs <= state.lastSeen) return null;
  const awaySeconds = (nowMs - state.lastSeen) / 1000;
  if (awaySeconds < 60) return null;
  const mods = getModifiers(state);
  const countedSeconds = Math.min(awaySeconds, mods.offlineHours * 3600);
  const lumens = passiveRate(state, false) * mods.offlineEfficiency * countedSeconds;
  if (!(lumens > 0)) return null;
  return { awaySeconds, countedSeconds, efficiency: mods.offlineEfficiency, lumens };
}

// ---------------------------------------------------------------- events

/** Seconds until the next shoal, given a random number in [0, 1). */
export function shoalDelay(state: GameState, roll: number): number {
  const mean = SHOAL_INTERVAL / getModifiers(state).shoalRate;
  return mean * (0.75 + roll * 0.5);
}

// ---------------------------------------------------------------- daily gift

/** The daily gift is worth this many minutes of fleet income... */
export const DAILY_MINUTES = 10;
/** ...plus this share per day of streak, up to DAILY_MAX_STREAK days. */
export const DAILY_STREAK_BONUS = 0.1;
export const DAILY_MAX_STREAK = 10;
/** The gift appears once the player has dived this far at least once (100 m). */
export const DAILY_UNLOCK_STEP = 10;

/** Local calendar day number for a wall-clock time. */
export function localDay(nowMs: number, timezoneOffsetMinutes: number): number {
  return Math.floor((nowMs - timezoneOffsetMinutes * 60_000) / 86_400_000);
}

export function dailyAvailable(state: GameState, today: number): boolean {
  return state.maxStepEver >= DAILY_UNLOCK_STEP && today > state.dailyDay;
}

/** Streak the player would be on after claiming today. */
export function dailyStreakAfterClaim(state: GameState, today: number): number {
  return today === state.dailyDay + 1 ? Math.min(DAILY_MAX_STREAK, state.dailyStreak + 1) : 1;
}

export function dailyReward(state: GameState, today: number): number {
  const streak = dailyStreakAfterClaim(state, today);
  const multiplier = 1 + DAILY_STREAK_BONUS * (streak - 1);
  return Math.max(passiveRate(state, false) * DAILY_MINUTES * 60, 60 * tapValue(state, false)) * multiplier;
}
